import { HomeAssistant } from 'custom-card-helpers';
import { LitElement } from 'lit';
import '../src/ha-sankey-chart';
import SankeyChart from '../src/ha-sankey-chart';
import { EDITOR_BRIDGE, PreviewAction, SankeyEditorBridge } from '../src/editor-bridge';
import type { SankeyChartConfig } from '../src/types';
import mockHass from './__mocks__/hass.mock';

const hass = mockHass({
  ent1: { entity_id: 'ent1', state: '2', attributes: { unit_of_measurement: 'W' } },
  ent2: { entity_id: 'ent2', state: '2', attributes: { unit_of_measurement: 'W' } },
  zero: { entity_id: 'zero', state: '0', attributes: { unit_of_measurement: 'W' } },
});

// ids without a dot are not auto-generated by the hass mock, so this one is missing
const MISSING = 'missingentity';

const baseConfig = (): SankeyChartConfig => ({
  type: 'custom:sankey-chart',
  nodes: [
    { id: 'ent1', section: 0 },
    { id: 'ent2', section: 1 },
    { id: 'zero', section: 1 },
    { id: MISSING, section: 1 },
  ],
  links: [
    { source: 'ent1', target: 'ent2' },
    { source: 'ent1', target: 'zero' },
    { source: 'ent1', target: MISSING },
  ],
  sections: [{}, {}, {}],
});

// boxes render in config order: section 0, then section 1
const BOX_ORDER = ['ent1', 'ent2', 'zero', MISSING];
const boxOf = (root: ShadowRoot, id: string) => root.querySelectorAll('g.box')[BOX_ORDER.indexOf(id)] as SVGGElement;

const pointer = (type: string, init: MouseEventInit = {}, pointerId = 1, pointerType = 'mouse') => {
  const ev = new MouseEvent(type, { bubbles: true, composed: true, button: 0, ...init });
  Object.defineProperty(ev, 'pointerId', { value: pointerId });
  Object.defineProperty(ev, 'pointerType', { value: pointerType });
  return ev;
};

describe('preview editing', () => {
  let card: SankeyChart;
  let actions: PreviewAction[];
  let bridge: SankeyEditorBridge;

  const mount = async (config: SankeyChartConfig) => {
    card.setConfig(config, true);
    document.body.appendChild(card);
    await card.updateComplete;
    const base = card.shadowRoot!.querySelector('sankey-chart-base') as LitElement;
    await base.updateComplete;
    return base.shadowRoot!;
  };

  // jsdom has no hui-error-card; give renderError something to create
  const win = window as unknown as { loadCardHelpers?: unknown };
  beforeAll(() => {
    win.loadCardHelpers = async () => ({ createCardElement: () => document.createElement('div') });
  });
  afterAll(() => {
    delete win.loadCardHelpers;
  });

  beforeEach(() => {
    actions = [];
    bridge = new SankeyEditorBridge(action => actions.push(action));
    bridge.setActive(true);
    card = document.createElement('sankey-chart') as SankeyChart;
    // @ts-ignore
    card.hass = hass as HomeAssistant;
  });

  afterEach(() => {
    card.remove();
  });

  it('draws hidden and missing nodes, empty sections and zero-flow links', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);

    expect(root.querySelector('.container.editing')).not.toBeNull();
    expect(root.querySelectorAll('g.box')).toHaveLength(4);
    expect(root.querySelectorAll('g.box.ghost')).toHaveLength(2);
    expect(root.querySelectorAll('g.box.missing')).toHaveLength(1);
    expect(root.querySelectorAll('rect.empty-section')).toHaveLength(1);
    expect(root.querySelectorAll('.ghost-link')).toHaveLength(2);
    // section 2 exists (empty), so every node can start a link
    expect(root.querySelectorAll('.link-handle')).toHaveLength(4);
  });

  it('keeps the regular rendering without an active editor', async () => {
    bridge.setActive(false);
    const config = baseConfig();
    config.nodes = config.nodes!.filter(n => n.id !== MISSING);
    config.links = config.links!.filter(l => l.target !== MISSING);
    const root = await mount({ ...config, [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);

    expect(root.querySelector('.container.editing')).toBeNull();
    expect(root.querySelectorAll('g.box')).toHaveLength(2);
    expect(root.querySelector('.link-handle')).toBeNull();
  });

  it('tolerates half-built graphs while editing', async () => {
    const root = await mount({
      type: 'custom:sankey-chart',
      nodes: [
        { id: 'ent1', section: 0 },
        { id: 'orphan', section: 1, type: 'remaining_parent_state' },
        { id: 'pass', section: 1, type: 'passthrough' },
      ],
      links: [
        { source: 'ent1', target: 'pass' },
        { source: 'ent1', target: 'gone' },
      ],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig);

    expect(root.querySelectorAll('g.box')).toHaveLength(3);
  });

  it('tolerates remainders without resolvable flows, also when converting units', async () => {
    const root = await mount({
      type: 'custom:sankey-chart',
      convert_units_to: 'MJ',
      nodes: [
        { id: 'ent1', section: 0 },
        { id: 'rest', section: 1, type: 'remaining_child_state' },
        { id: 'orphan', section: 1, type: 'remaining_parent_state' },
        { id: 'pass', section: 2, type: 'passthrough' },
      ],
      links: [
        { source: 'ent1', target: 'rest' },
        { source: 'rest', target: 'pass' },
        { source: 'rest', target: 'gone' },
      ],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig);

    expect(root.querySelectorAll('g.box')).toHaveLength(4);
  });

  it('computes icons for placeholder nodes without crashing', async () => {
    // the global mock hides that stateIcon needs an entity_id
    const helpers = jest.requireActual('custom-card-helpers');
    const mocked = jest.requireMock('custom-card-helpers').stateIcon as jest.Mock;
    mocked.mockImplementation(helpers.stateIcon);
    try {
      const root = await mount({
        type: 'custom:sankey-chart',
        nodes: [
          { id: 'ent1', section: 0 },
          { id: MISSING, section: 1 },
          { id: 'floor', section: 1, type: 'remaining_child_state' },
          { id: 'orphan', section: 1, type: 'remaining_parent_state' },
        ],
        links: [{ source: 'ent1', target: MISSING }],
        [EDITOR_BRIDGE]: bridge,
      } as SankeyChartConfig);
      expect(root.querySelectorAll('g.box')).toHaveLength(4);
    } finally {
      mocked.mockReturnValue('state-icon');
    }
  });

  it('resolves units for remainders that only lead to each other', async () => {
    // a remaining_child_state feeding a remaining_parent_state: each would read the other for its unit
    const cycle = {
      type: 'custom:sankey-chart',
      nodes: [
        { id: 'ent1', section: 0 },
        { id: 'rest', section: 1, type: 'remaining_child_state' },
        { id: 'left', section: 2, type: 'remaining_parent_state' },
      ],
      links: [
        { source: 'ent1', target: 'rest' },
        { source: 'rest', target: 'left' },
      ],
    } as SankeyChartConfig;
    const root = await mount({ ...cycle, [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    expect(root.querySelectorAll('g.box')).toHaveLength(3);

    card.remove();
    card = document.createElement('sankey-chart') as SankeyChart;
    // @ts-ignore
    card.hass = hass as HomeAssistant;
    const normal = await mount(cycle);
    expect(normal.querySelector('svg.chart')).not.toBeNull();
  });

  it('fits a vertical preview with many hidden nodes instead of overlapping them', async () => {
    const zeros = Array.from({ length: 150 }, (_, i) => ({ id: `zero${i}`, section: 1 }));
    const root = await mount({
      type: 'custom:sankey-chart',
      layout: 'vertical',
      nodes: [{ id: 'ent1', section: 0 }, { id: 'ent2', section: 1 }, ...zeros],
      links: [{ source: 'ent1', target: 'ent2' }],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig);

    const bars = [...root.querySelectorAll('g.box.ghost rect.color-bar')].map(r => ({
      x: Number(r.getAttribute('x')),
      width: Number(r.getAttribute('width')),
    }));
    expect(bars).toHaveLength(150);
    bars.slice(1).forEach((bar, i) => {
      expect(bar.x).toBeGreaterThanOrEqual(bars[i].x + bars[i].width);
    });
    const viewBox = root.querySelector('svg.chart')!.getAttribute('viewBox')!.split(' ').map(Number);
    expect(viewBox[2]).toBeGreaterThanOrEqual(bars[bars.length - 1].x + bars[bars.length - 1].width);
  });

  it('reports the graph of an autoconfig chart pasted with its nodes', async () => {
    const hop = 'ent2__passthrough_1__auto';
    await mount({
      type: 'custom:sankey-chart',
      // power mode reads live states, so the test needs no energy collection
      autoconfig: { mode: 'power', print_yaml: false },
      nodes: [{ id: 'ent1', section: 0 }, { id: hop, section: 1, type: 'passthrough' }, { id: 'ent2', section: 2 }],
      links: [
        { source: 'ent1', target: hop },
        { source: hop, target: 'ent2' },
      ],
      sections: [{}, { sort_by: 'state' }, {}],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig);

    expect(bridge.generated?.nodes.map(n => n.id)).toEqual(['ent1', 'ent2']);
    expect(bridge.generated?.links).toEqual([{ source: 'ent1', target: 'ent2' }]);
    expect(bridge.generated?.sections).toEqual([{}, { sort_by: 'state' }, {}]);
  });

  it('recovers when the editor comes back after rendering without it', async () => {
    const config = {
      type: 'custom:sankey-chart',
      nodes: [
        { id: 'ent1', section: 0 },
        { id: 'pass', section: 1, type: 'passthrough' },
      ],
      links: [{ source: 'ent1', target: 'pass' }],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig;
    let root = await mount(config);
    const base = card.shadowRoot!.querySelector('sankey-chart-base') as LitElement;
    expect(root.querySelector('svg.chart')).not.toBeNull();

    // e.g. the user opened the visibility tab, which disconnects the editor;
    // without it the half-built graph is an error again
    bridge.setActive(false);
    await base.updateComplete;
    expect(base.shadowRoot!.querySelector('svg.chart')).toBeNull();
    bridge.setActive(true);
    await base.updateComplete;
    root = base.shadowRoot!;
    expect(root.querySelector('.container.editing svg.chart')).not.toBeNull();
  });

  it('lets only one card edit through a bridge', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    expect(root.querySelector('.container.editing')).not.toBeNull();

    // what HA does on save: the dashboard card gets the preview's config while the dialog is open
    const dashboardCard = document.createElement('sankey-chart') as SankeyChart;
    // @ts-ignore
    dashboardCard.hass = hass as HomeAssistant;
    const config = baseConfig();
    config.nodes = config.nodes!.filter(n => n.id !== MISSING);
    config.links = config.links!.filter(l => l.target !== MISSING);
    dashboardCard.setConfig({ ...config, [EDITOR_BRIDGE]: bridge } as SankeyChartConfig, true);
    document.body.appendChild(dashboardCard);
    await dashboardCard.updateComplete;
    const dashboardBase = dashboardCard.shadowRoot!.querySelector('sankey-chart-base') as LitElement;
    await dashboardBase.updateComplete;
    expect(dashboardBase.shadowRoot!.querySelector('svg.chart')).not.toBeNull();
    expect(dashboardBase.shadowRoot!.querySelector('.container.editing')).toBeNull();
    dashboardCard.remove();
  });

  it('grows the preview so many hidden nodes stay reachable', async () => {
    const nodes = Array.from({ length: 20 }, (_, i) => ({ id: `zero${i}`, section: 1 }));
    const root = await mount({
      type: 'custom:sankey-chart',
      height: 200,
      nodes: [{ id: 'ent1', section: 0 }, { id: 'ent2', section: 1 }, ...nodes],
      links: [{ source: 'ent1', target: 'ent2' }],
      [EDITOR_BRIDGE]: bridge,
    } as SankeyChartConfig);

    const svg = root.querySelector('svg.chart')!;
    expect(Number(svg.getAttribute('height'))).toBeGreaterThan(200);
    const ghostBars = [...root.querySelectorAll('g.box.ghost rect.color-bar')].map(r => ({
      y: Number(r.getAttribute('y')),
      height: Number(r.getAttribute('height')),
    }));
    expect(ghostBars).toHaveLength(20);
    ghostBars.slice(1).forEach((bar, i) => {
      expect(bar.y).toBeGreaterThanOrEqual(ghostBars[i].y + ghostBars[i].height);
    });
  });

  it('applies a highlight the editor set before the preview was rebuilt', async () => {
    bridge.setHighlight('ent2');
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    const base = card.shadowRoot!.querySelector('sankey-chart-base') as LitElement;
    await base.updateComplete;
    expect(root.querySelectorAll('g.box.hl').length).toBeGreaterThan(0);
  });

  it('marks the selection sent by the editor', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    const base = card.shadowRoot!.querySelector('sankey-chart-base') as LitElement;

    bridge.setSelection({ type: 'node', id: 'ent2' });
    await base.updateComplete;
    const selected = root.querySelectorAll('g.box.selected');
    expect(selected).toHaveLength(1);
    expect(selected[0].querySelector('.selection-ring')).not.toBeNull();

    bridge.setSelection({ type: 'link', source: 'ent1', target: 'zero' });
    await base.updateComplete;
    expect(root.querySelectorAll('.ghost-link.selected')).toHaveLength(1);
  });

  it('reports clicks, deselection and keyboard shortcuts to the editor', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    const box = root.querySelector('g.box') as SVGGElement;
    const svg = root.querySelector('svg.chart') as SVGSVGElement;

    box.dispatchEvent(pointer('pointerdown'));
    box.dispatchEvent(pointer('pointerup'));
    expect(actions).toEqual([{ type: 'select', selection: { type: 'node', id: 'ent1' } }]);

    bridge.setSelection({ type: 'node', id: 'ent1' });
    svg.dispatchEvent(new KeyboardEvent('keydown', { key: 'Delete', bubbles: true }));
    svg.dispatchEvent(new KeyboardEvent('keydown', { key: 'z', ctrlKey: true, bubbles: true }));
    svg.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    svg.dispatchEvent(pointer('pointerdown'));
    svg.dispatchEvent(pointer('pointerup'));
    expect(actions.slice(1)).toEqual([
      { type: 'remove', selection: { type: 'node', id: 'ent1' } },
      { type: 'undo' },
      { type: 'select', selection: undefined },
      { type: 'select', selection: undefined },
    ]);
  });

  describe('dragging', () => {
    // jsdom has no SVG geometry: make client coordinates equal chart coordinates
    beforeAll(() => {
      (globalThis as unknown as { DOMPoint: unknown }).DOMPoint = class {
        constructor(public x: number, public y: number) {}
        matrixTransform() {
          return { x: this.x, y: this.y };
        }
      };
    });

    const prepare = async (config: SankeyChartConfig) => {
      const root = await mount({ ...config, [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
      const svg = root.querySelector('svg.chart') as SVGSVGElement;
      Object.defineProperty(svg, 'getScreenCTM', { value: () => ({ inverse: () => ({}) }) });
      const center = (id: string) => {
        const bar = boxOf(root, id).querySelector('rect.color-bar')!;
        const x = Number(bar.getAttribute('x')) + Number(bar.getAttribute('width')) / 2;
        const y = Number(bar.getAttribute('y')) + Number(bar.getAttribute('height')) / 2;
        return { clientX: x, clientY: y };
      };
      const emptyColumn = root.querySelector('rect.empty-section')!;
      const empty = {
        clientX: Number(emptyColumn.getAttribute('x')) + 10,
        clientY: Number(emptyColumn.getAttribute('y')) + 10,
      };
      return { root, svg, center, empty };
    };

    it('moves a node into another section', async () => {
      const { root, svg, center, empty } = await prepare(baseConfig());
      const box = boxOf(root, 'ent2');

      box.dispatchEvent(pointer('pointerdown', center('ent2')));
      svg.dispatchEvent(pointer('pointermove', { clientX: center('ent2').clientX + 10, clientY: center('ent2').clientY }));
      svg.dispatchEvent(pointer('pointermove', empty));
      svg.dispatchEvent(pointer('pointerup', empty));

      expect(actions).toEqual([{ type: 'move_node', id: 'ent2', section: 2 }]);
    });

    it('links two nodes from the handle', async () => {
      const config = baseConfig();
      config.links = config.links!.filter(l => l.target !== 'zero');
      const { root, svg, center } = await prepare(config);
      const handle = root.querySelector('.link-handle') as SVGGElement;

      handle.dispatchEvent(pointer('pointerdown', center('ent1')));
      svg.dispatchEvent(pointer('pointermove', center('zero')));
      svg.dispatchEvent(pointer('pointerup', center('zero')));

      expect(actions).toEqual([{ type: 'add_link', source: 'ent1', target: 'zero' }]);
    });

    it('offers a new linked node when the link ends in empty space', async () => {
      const { root, svg, center, empty } = await prepare(baseConfig());
      const ent2Handle = boxOf(root, 'ent2').querySelector('.link-handle')!;

      ent2Handle.dispatchEvent(pointer('pointerdown', center('ent2')));
      svg.dispatchEvent(pointer('pointermove', empty));
      svg.dispatchEvent(pointer('pointerup', empty));

      expect(actions).toEqual([{ type: 'add_node', section: 2, link_from: 'ent2' }]);
    });

    it('ignores a second pointer while dragging', async () => {
      const { svg, center, empty } = await prepare(baseConfig());
      const root = card.shadowRoot!.querySelector('sankey-chart-base')!.shadowRoot!;
      const box = boxOf(root, 'ent2');

      box.dispatchEvent(pointer('pointerdown', center('ent2')));
      svg.dispatchEvent(pointer('pointermove', empty));
      boxOf(root, 'ent1').dispatchEvent(pointer('pointerdown', center('ent1'), 2));
      svg.dispatchEvent(pointer('pointerup', center('ent1'), 2));
      expect(actions).toEqual([]);

      svg.dispatchEvent(pointer('pointerup', empty));
      expect(actions).toEqual([{ type: 'move_node', id: 'ent2', section: 2 }]);
    });

    it('treats a slightly jittery tap as a click', async () => {
      const { root, svg, center } = await prepare(baseConfig());
      const start = center('ent2');
      const moved = { clientX: start.clientX + 6, clientY: start.clientY };

      boxOf(root, 'ent2').dispatchEvent(pointer('pointerdown', start, 1, 'touch'));
      svg.dispatchEvent(pointer('pointermove', moved, 1, 'touch'));
      svg.dispatchEvent(pointer('pointerup', moved, 1, 'touch'));

      expect(actions).toEqual([{ type: 'select', selection: { type: 'node', id: 'ent2' } }]);
    });

    it('ignores links that already exist', async () => {
      const { root, svg, center } = await prepare(baseConfig());
      const handle = root.querySelector('.link-handle') as SVGGElement;

      handle.dispatchEvent(pointer('pointerdown', center('ent1')));
      svg.dispatchEvent(pointer('pointermove', center('ent2')));
      svg.dispatchEvent(pointer('pointerup', center('ent2')));

      expect(actions).toEqual([]);
    });
  });

  it('makes HA compare bridges by identity, not by walking into the preview card', () => {
    // HA's deepEqual returns a.valueOf() === b.valueOf() when valueOf is overridden
    const other = new SankeyEditorBridge();
    expect(bridge.valueOf()).toBe(bridge);
    expect(bridge.valueOf() === other.valueOf()).toBe(false);
  });

  it('shows the focus ring after keyboard use only', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    const base = card.shadowRoot!.querySelector('sankey-chart-base') as LitElement;
    const svg = root.querySelector('svg.chart') as SVGSVGElement;
    const container = () => root.querySelector('.container')!;

    // focus without a press, as Tab does
    svg.focus();
    await base.updateComplete;
    expect(container().classList.contains('focus-ring')).toBe(true);

    boxOf(root, 'ent1').dispatchEvent(pointer('pointerdown'));
    svg.dispatchEvent(pointer('pointerup'));
    await base.updateComplete;
    expect(container().classList.contains('focus-ring')).toBe(false);
    // a rebuilt preview starts from the same state
    expect(bridge.focusRing).toBe(false);

    svg.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
    await base.updateComplete;
    expect(container().classList.contains('focus-ring')).toBe(true);
  });

  it('does not run tap actions while editing', async () => {
    const root = await mount({ ...baseConfig(), [EDITOR_BRIDGE]: bridge } as SankeyChartConfig);
    const moreInfo = jest.fn();
    card.addEventListener('hass-more-info', moreInfo);
    (root.querySelector('g.box') as SVGGElement).dispatchEvent(new MouseEvent('click', { bubbles: true, composed: true }));
    expect(moreInfo).not.toHaveBeenCalled();
  });
});
